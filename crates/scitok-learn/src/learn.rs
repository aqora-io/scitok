//! Mine cached records into domain files: `mined.toml`, `stats.toml` and
//! `stopword_candidates.txt` (the latter for review, never loaded).

use std::fmt::Write as _;
use std::fs;
use std::path::Path;

use scitok::domain::{FORMAT_VERSION, Stats};
use scitok::mine::{MineConfig, MineResult, Miner, Source};
use scitok::{Config, Domain, Input, Tokenizer};

use crate::cache::{Cache, Record};
use crate::oai::Filter;

pub struct BuildReport {
    pub abstracts: usize,
    pub fulltexts: usize,
    pub terms: usize,
    pub avg_len: f32,
}

pub fn build(cache: &Cache, filter: &Filter, out: &Path, cfg: MineConfig) -> Result<BuildReport, String> {
    let records: Vec<Record> = cache.records()?.into_iter().filter(|r| filter.accepts(r)).collect();
    if records.is_empty() {
        return Err(format!(
            "no cached {} records in {}..{}; run `scitok-learn fetch` first",
            filter.category, filter.from, filter.until
        ));
    }
    fs::create_dir_all(out).map_err(|e| format!("{}: {e}", out.display()))?;
    // Mine against the curated lexicon only, so the mined file is regenerated
    // from scratch rather than accumulating.
    // Only curated.toml/stopwords.txt are read: stale or broken generated
    // files must not prevent their regeneration.
    let read = |file: &str| fs::read_to_string(out.join(file)).ok();
    let curated = Domain::from_sources(
        &filter.category,
        read("curated.toml").as_deref(),
        None,
        None,
        read("stopwords.txt").as_deref(),
    )
    .map_err(|e| e.to_string())?;
    let tok = tokenizer(vec![curated.clone()]);

    let docs: Vec<String> = records.iter().map(document).collect();
    let fulltexts: Vec<String> = records.iter().filter_map(|r| cache.fulltext(&r.id)).collect();
    eprintln!("mining {} abstracts and {} full texts", docs.len(), fulltexts.len());
    let mut miner = Miner::new(&tok, cfg);
    for d in &docs {
        miner.add(d, Input::Auto, true);
    }
    for t in &fulltexts {
        miner.add(t, Input::Latex, false);
    }
    let result = miner.finish();

    let mut domain = curated;
    domain.mined = result.terms.iter().map(|t| t.def.clone()).collect();
    let tok = tokenizer(vec![domain]);
    let avg = |texts: &[String], input| texts.iter().map(|t| tok.len_as(t, input)).sum::<usize>() as f32 / texts.len().max(1) as f32;
    let stats = Stats {
        version: FORMAT_VERSION,
        category: filter.category.clone(),
        from: filter.from.to_string(),
        until: filter.until.to_string(),
        generated_by: format!("scitok-learn {}", env!("CARGO_PKG_VERSION")),
        docs: docs.len(),
        avg_len: round(avg(&docs, Input::Auto)),
        fulltext_docs: fulltexts.len(),
        avg_len_fulltext: (!fulltexts.is_empty()).then(|| round(avg(&fulltexts, Input::Latex))),
    };

    write(&out.join("mined.toml"), &mined_toml(&result, &stats))?;
    // a reviewed lexicon derived from the previous mined.toml would shadow the new one
    let reviewed = out.join("reviewed.toml");
    if reviewed.exists() {
        fs::remove_file(&reviewed).map_err(|e| format!("{}: {e}", reviewed.display()))?;
        eprintln!("removed stale {}; run `scitok-learn refine` again", reviewed.display());
    }
    write(&out.join("stats.toml"), &format!("# Generated by scitok-learn; do not edit.\n{}", toml::to_string(&stats).unwrap()))?;
    write(&out.join("stopword_candidates.txt"), &stopword_candidates(&result))?;
    Ok(BuildReport { abstracts: docs.len(), fulltexts: fulltexts.len(), terms: result.terms.len(), avg_len: stats.avg_len })
}

/// A tokenizer over `domains` with otherwise default settings.
pub fn tokenizer(domains: Vec<Domain>) -> Tokenizer {
    let mut config = Config::default();
    config.domains = domains;
    Tokenizer::new(config)
}

/// Title and abstract as one document, as they should be indexed.
pub fn document(r: &Record) -> String {
    format!("{}.\n{}", r.title, r.abstract_)
}

fn round(x: f32) -> f32 {
    (x * 10.0).round() / 10.0
}

fn write(path: &Path, content: &str) -> Result<(), String> {
    fs::write(path, content).map_err(|e| format!("{}: {e}", path.display()))
}

fn mined_toml(result: &MineResult, stats: &Stats) -> String {
    let q = |s: &str| toml::Value::String(s.to_owned()).to_string();
    let mut out = format!(
        "# Mined {} lexicon: {} abstracts, {} full texts, {}..{}.\n\
         # Generated by {}; do not edit. Override or extend entries in curated.toml.\n\
         version = {FORMAT_VERSION}\n",
        stats.category, stats.docs, stats.fulltext_docs, stats.from, stats.until, stats.generated_by
    );
    for (source, title) in [(Source::Acronym, "Acronyms"), (Source::Eponym, "Eponyms"), (Source::Collocation, "Collocations")] {
        let terms: Vec<_> = result.terms.iter().filter(|t| t.source == source).collect();
        if terms.is_empty() {
            continue;
        }
        write!(out, "\n# --- {title} ({}) ---\n", terms.len()).unwrap();
        for t in terms {
            let strength = match source {
                Source::Acronym => format!(" share={:.2}", t.strength),
                Source::Collocation => format!(" npmi={:.2}", t.strength),
                Source::Eponym => String::new(),
            };
            write!(out, "\n[[term]] # df={}{strength}\ncanonical = {}\nvariants = [", t.df, q(&t.def.canonical)).unwrap();
            let variants: Vec<String> = t.def.variants.iter().map(|v| q(v)).collect();
            out.push_str(&variants.join(", "));
            out.push_str("]\n");
            if t.def.case_sensitive {
                out.push_str("case_sensitive = true\n");
            }
        }
    }
    out
}

fn stopword_candidates(result: &MineResult) -> String {
    let mut out = String::from(
        "# Words in a large share of documents (document frequency ratio).\n\
         # Not loaded: copy real boilerplate into stopwords.txt after review.\n",
    );
    for (word, ratio) in &result.stopword_candidates {
        writeln!(out, "{word}\t{ratio:.3}").unwrap();
    }
    out
}

#[cfg(test)]
mod tests {
    use super::*;
    use chrono::NaiveDate;

    #[test]
    fn builds_domain_files_that_load() {
        let root = std::env::temp_dir().join(format!("scitok-learn-build-{}", std::process::id()));
        let _ = fs::remove_dir_all(&root);
        let mut cache = Cache::open(&root.join("cache"), "quant-ph").unwrap();
        let records: Vec<Record> = (0..12)
            .map(|i| Record {
                id: format!("2610.{i:05}"),
                datestamp: "2026-10-01".into(),
                categories: vec!["quant-ph".into()],
                title: format!("Paper {i} on the frobnicated quantum widget"),
                abstract_: format!(
                    "We study the frobnicated quantum widget (FQW) with $n={i}$ qubits. \
                     The Smith-Jones inequality bounds FQW noise. Item{i} differs."
                ),
                ..Record::default()
            })
            .collect();
        cache.append(&records).unwrap();
        let out = root.join("domain");
        fs::create_dir_all(&out).unwrap();
        fs::write(out.join("curated.toml"), "version = 1\n[[term]]\ncanonical = \"qubit\"\nvariants = [\"qubit\"]\n").unwrap();
        let filter = Filter {
            category: "quant-ph".into(),
            from: NaiveDate::from_ymd_opt(2026, 4, 1).unwrap(),
            until: NaiveDate::from_ymd_opt(2026, 10, 15).unwrap(),
            include_cross_lists: false,
            include_revisions: false,
        };
        let report = build(&cache, &filter, &out, MineConfig { min_count: 3, ..MineConfig::default() }).unwrap();
        assert_eq!(report.abstracts, 12);
        let mined = fs::read_to_string(out.join("mined.toml")).unwrap();
        assert!(mined.contains("canonical = \"fqw\""), "{mined}");
        assert!(mined.contains("canonical = \"smith_jones_inequality\""), "{mined}");

        let domain = Domain::load(&out).unwrap();
        assert_eq!(domain.curated.len(), 1);
        assert!(domain.stats.as_ref().unwrap().avg_len > 5.0);
        let tok = tokenizer(vec![domain]);
        assert!(tok.tokenize("an FQW").contains(&"~fqw".to_string()));

        // rebuilding is deterministic
        build(&cache, &filter, &out, MineConfig { min_count: 3, ..MineConfig::default() }).unwrap();
        assert_eq!(fs::read_to_string(out.join("mined.toml")).unwrap(), mined);
        fs::remove_dir_all(root).unwrap();
    }
}
